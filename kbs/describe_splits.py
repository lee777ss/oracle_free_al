"""kbs.describe_splits - the data table of the revised paper (R1.3), derived from the v2 data layer.

    python -m kbs.describe_splits            # print the table
    python -m kbs.describe_splits --write    # also write src/generated/tbl_data.tex and tbl_data.json

Every count is computed, none is typed: official split sizes of the three classes, development set,
reservoir, pool, training portion and hold-out after the 90/10 split, both test evaluations, the
augmentation ratio r, the synthetic images per minority class and the acquisition cycles T of the
proposed method. Pool sizes do not depend on the seed (only which images are drawn does).
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np
from sklearn.model_selection import StratifiedShuffleSplit

from kbs import PAPER_DIR
from casestudy.protocol_v2 import REGIMES_V2, _raw, get_regime, make_config, regime_spec

PAPER = PAPER_DIR
NAMES = {"fashion_mnist": "Fashion-MNIST", "cifar10": "CIFAR-10", "stl10": "STL-10", "octmnist": "OCTMNIST",
         "gtsrb": "GTSRB"}


def describe(regime: str, cfg) -> dict:
    info = REGIMES_V2[regime]
    rd = get_regime(regime, cfg)
    spec = rd.spec
    raw = _raw(info["dataset"], spec, cfg)
    K = rd.K
    res = np.bincount(rd.res_y, minlength=K)
    n_maj = int(min(res[0], spec.majority_cap)) if spec.majority_cap else int(res[0])
    n_min = int(round(info["rho"] * n_maj))
    pool = [n_maj] + [min(n_min, int(res[c])) for c in range(1, K)]
    labels = np.repeat(np.arange(K), pool)
    tr, ho = next(StratifiedShuffleSplit(n_splits=1, test_size=0.1, random_state=0).split(np.zeros(len(labels)), labels))
    train, hold = np.bincount(labels[tr], minlength=K).tolist(), np.bincount(labels[ho], minlength=K).tolist()
    r = info["ratio"]
    target = [train[0]] + [min(train[0], max(n, round((float(r) if r != "full" else 1e9) * n))) for n in train[1:]]
    synth = [t - n for t, n in zip(target, train)]
    official_train = (np.bincount(raw["res_y"], minlength=K) + np.bincount(raw["dev_y"], minlength=K)).tolist()
    return {
        "regime": regime, "dataset": NAMES[info["dataset"]], "classes": list(spec.class_names), "rho": info["rho"],
        "official_train": official_train, "dev": np.bincount(raw["dev_y"], minlength=K).tolist(),
        "dropped_duplicates": raw["n_dup"], "reservoir": res.tolist(), "pool": pool, "train": train, "holdout": hold,
        "test": rd.counts["test"], "test_full": rd.counts["test_full"], "primary": rd.primary, "ratio": str(r),
        "synthetic_per_class": synth[1:], "augmented_train": target,
        "cycles_T": int(math.ceil(max(synth[1:]) / 20)) if max(synth[1:]) > 0 else 0,
    }


def _fmt(v) -> str:
    return ":".join(str(x) for x in v)


def to_latex(rows) -> str:
    lines = [
        r"% Generated by kbs/describe_splits.py - do not edit by hand.",
        r"\providecommand{\revtable}{}  % the manuscript colours tables added in the revision",
        r"\begin{table}[htbp]",
        r"\revtable",
        r"\centering",
        r"\caption{Data of every regime. Counts are majority : minority : minority. The pool is drawn anew for each "
        r"seed from the official training images that remain after a fixed development set has been set aside; its "
        r"composition does not depend on the seed. Ten per cent of the pool is held out for model selection. "
        r"Each augmenter adds the same number of synthetic images per minority class. "
        r"No image is unlabelled.}",
        r"\label{tbl:data}",
        r"\resizebox{\ifdim\width>\linewidth\linewidth\else\width\fi}{!}{\scalebox{0.62}{",   # fit if still too wide
        r"\begin{tabular}{llcccccccc}",
        r"\toprule",
        r"Dataset & Classes & $\rho$ & Pool & Training / hold-out & Test & Full test & $r$ & Synthetic per class & $T$ \\",
        r"\midrule",
    ]
    for d in rows:
        lines.append(f"{d['dataset']} & {', '.join(d['classes'])} & {d['rho']:g} & {_fmt(d['pool'])} & "
                     f"{_fmt(d['train'])} / {_fmt(d['holdout'])} & {_fmt(d['test'])} & {_fmt(d['test_full'])} & "
                     f"{d['ratio']} & {d['synthetic_per_class'][0]} & {d['cycles_T']} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}}}", r"\end{table}", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    cfg = make_config()
    rows = [describe(r, cfg) for r in REGIMES_V2]
    for d in rows:
        print(f"{d['regime']:22s} {d['dataset']:13s} rho={d['rho']:<6g} pool {_fmt(d['pool']):14s} train {_fmt(d['train']):14s} "
              f"hold-out {_fmt(d['holdout']):10s} test {_fmt(d['test']):14s} full {_fmt(d['test_full']):16s} r={d['ratio']:4s} "
              f"synthetic {d['synthetic_per_class'][0]:4d}/class  T={d['cycles_T']:2d}  dev {_fmt(d['dev'])}  "
              f"duplicates dropped {d['dropped_duplicates']}")
    if args.write:
        out = PAPER / "src" / "generated"
        out.mkdir(parents=True, exist_ok=True)
        (out / "tbl_data.tex").write_text(to_latex(rows), encoding="utf-8")
        (out / "tbl_data.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
        print("written:", out / "tbl_data.tex")


if __name__ == "__main__":
    main()

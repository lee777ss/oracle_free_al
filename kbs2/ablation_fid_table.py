"""kbs2.ablation_fid_table - Table 4 and Figure A2 of the revision from the fifteen-seed ablation (R1.9).

    python -m kbs2.ablation_fid_table   # writes src/generated/rev2_ablation_fid.tex and figures/final/fid_15seeds.pdf

Authors 13 Oct 2026: Table 4 rebuilt on the basis of Table 3 panel A (seeds 42-56), one autoencoder row per
backbone; order autoencoder (BAGAN), autoencoder (BAGAN-GP), BAGAN, BAGAN-GP; no Proposed row (second revision).
Sources: saved/ae_fid_133J_s<seed>_<backbone>.npz (autoencoder), ablation_15_seeds.csv (backbone generator before
the acquisition loop; identical for every row of a backbone, checked here).
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEX = os.path.join(ROOT, "Journal_paper_02_kbs_revise2", "src", "generated", "rev2_ablation_fid.tex")
FIG = os.path.join(ROOT, "Journal_paper_02_kbs_revise2", "figures", "final", "fid_15seeds.pdf")
SEEDS = range(42, 57)
CLS = ["fid_c0", "fid_c1", "fid_c2"]


def rows() -> list:
    """(label, {class: [15 values]}) in table order."""
    d = pd.read_csv(os.path.join(ROOT, "ablation_15_seeds.csv"))
    d = d[d["section"].astype(str).str.startswith("seed_")].copy()
    for c in CLS:
        d[c] = pd.to_numeric(d[c], errors="coerce")
    aes, gens = [], []
    for backbone, csv_rows, label in (("bagan", ["Baseline 1", "Variant 1", "Variant 2"], "BAGAN"),
                                      ("bagan_gp", ["Baseline 1a", "Variant 1a", "Variant 3"], "BAGAN-GP")):
        ae = {k: [] for k in range(3)}
        for s in SEEDS:
            z = np.load(os.path.join(ROOT, "saved", f"ae_fid_133J_s{s}_{backbone}.npz"))
            for k in range(3):
                ae[k].append(float(z["ae_fid"][k]))
        g = d[d["row"].isin(csv_rows)]
        per_seed = g.groupby("seed")[CLS].agg(lambda v: v.iloc[0] if v.nunique() == 1 else np.nan)
        if per_seed.isna().any().any() or len(per_seed) != 15:
            raise SystemExit(f"{backbone}: backbone FID differs between rows of a seed")
        gen = {k: per_seed[CLS[k]].tolist() for k in range(3)}
        aes.append((f"Autoencoder ({label})", ae))
        gens.append((label, gen))
    # Authors 13 Oct (third revision): the rows and names of the submitted table - Autoencoder (BAGAN backbone's),
    # Generative model (BAGAN), Proposed (BAGAN-GP generator before the acquisition loop).
    return [("Autoencoder", aes[0][1]), ("Generative model", gens[0][1]), ("Proposed", gens[1][1])]


def stats(v) -> tuple:
    v = np.asarray(v, dtype=float)
    return v.mean(), v.std(ddof=1)


def latex(table) -> str:
    lines = ["% Generated by kbs2/ablation_fid_table.py; do not edit.", r"\begin{table}[htbp]", r"\centering",
             r"\caption{Per-class Fr\'echet Inception Distance for the generators \rev{of the ablation study "
             r"(Table~\ref{tbl:ablation}, panel A), mean $\pm$ standard deviation over the fifteen seeds; "
             r"lower is better. Autoencoder: class-conditional samples decoded by the pretrained autoencoder; "
             # authors 17 Oct 2026: generators named as in Figure 2 (no BAGAN / Variant labels)
             r"Generative model and Proposed: the generative model and the Proposed generator of "
             r"Figure~\ref{fig:sample_grid}, both after adversarial training and before the "
             r"acquisition loop; 2000 generated images per class.}}",
             r"\label{tbl:ablation_fid}", r"\resizebox{\linewidth}{!}{", r"\begin{tabular}{lcccc}", r"\toprule",
             r"Generator & c0 (T-shirt/top) & c1 (Pullover) & c2 (Dress) & Minority mean \\", r"\midrule"]
    means = {}
    for label, v in table:
        cells = []
        for k in range(3):
            cells.append("--" if v[k] is None else "${:.1f} \\pm {:.1f}$".format(*stats(v[k])))
        mm = stats([(a + b) / 2 for a, b in zip(v[1], v[2])])
        means[label] = mm[0]
        cells.append("${:.1f} \\pm {:.1f}$".format(*mm))
        lines.append(rf"\rev{{{label}}} & " + " & ".join(rf"\rev{{{c}}}" for c in cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    return "\n".join(lines) + "\n", means


def figure(table) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    names = ["c0 (T-shirt/top)", "c1 (Pullover)", "c2 (Dress)", "Minority mean"]
    colors = ["#c6dbef", "#6baed6", "#08519c"]
    fig, ax = plt.subplots(figsize=(9, 3.6))
    w = 0.8 / len(table)
    for i, ((label, v), col) in enumerate(zip(table, colors)):
        vals = [v[k] for k in range(3)] + [[(a + b) / 2 for a, b in zip(v[1], v[2])]]
        m = [np.nan if x is None else np.mean(x) for x in vals]
        s = [0 if x is None else np.std(x, ddof=1) for x in vals]
        x = np.arange(4) + (i - (len(table) - 1) / 2) * w
        ax.bar(x, m, w * 0.92, yerr=s, capsize=2, color=col, edgecolor="black", linewidth=0.4,
               label=label.replace("--", "-"), error_kw={"linewidth": 0.6})
    ax.set_xticks(range(4)); ax.set_xticklabels(names)
    ax.set_ylabel("FID (lower is better)")
    ax.legend(ncol=3, fontsize=8, loc="upper center", bbox_to_anchor=(0.5, 1.13), frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(FIG, bbox_inches="tight")


def main() -> None:
    table = rows()
    tex, means = latex(table)
    with open(TEX, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(tex)
    figure(table)
    for k, v in means.items():
        print(f"{k:35s} minority mean {v:.1f}")


if __name__ == "__main__":
    main()

"""kbs2.classwise - class-wise precision and recall and confusion matrices for Table 6 (Reviewer 1, comment 8).

    python -m kbs2.classwise      # writes saved_kbs2/analysis/classwise/, the appendix table and the figure

Authors 13 Oct 2026: all ten methods of Table 6. No new run: the test-set predictions saved by the runs behind
Table 6 (classifier seed 42), the same sources as kbs2.table6_stats:
    proposed E1 (W) | naive E2 (W) | class-weighted E2t isqrt (W) | ROS E2z (U) | std. aug. E2s zc32 (W) |
    DCGAN, cGAN, ACGAN, WGAN-GP, BAGAN E8 (W)
E1, E2 (naive) and E8 reproduce the submitted per-seed metrics, so these predictions are those of Table 6.
Check: macro-recall recomputed from the predictions must equal the macro-recall recorded for the run.
Per class: recall and precision, mean over the ten seeds (SD in the CSV). Confusion matrices: row-normalised
(each row sums to one over the true class), averaged over seeds.
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from kbs2 import protocol as P  # noqa: E402

SAVED = os.path.join(ROOT, "saved_kbs2")
OUT = os.path.join(SAVED, "analysis", "classwise")
TEX = os.path.join(ROOT, "Journal_paper_02_kbs_revise2", "src", "generated", "rev2_classwise.tex")
FIG = os.path.join(ROOT, "Journal_paper_02_kbs_revise2", "figures", "final", "confusion.pdf")
os.makedirs(os.path.dirname(TEX), exist_ok=True)  # public release: create the output folder
os.makedirs(os.path.dirname(FIG), exist_ok=True)  # public release: create the output folder
# Row order and labels of Table 6: (label, experiment, file prefix, arm)
METHODS = [
    ("Imbalanced-naive", "E2", "m11_imbalanced_naive", "W"),
    ("Class-weighted", "E2t", "n01_class_weighted_isqrt", "W"),
    ("Random oversampling", "E2z", "n02_ros", "U"),
    (r"Std.\ augmentation", "E2s", "n08_stdaug_budget_zc32", "W"),
    ("DCGAN", "E8", "m04_dcgan", "W"),
    ("cGAN", "E8", "m05_cgan", "W"),
    ("ACGAN", "E8", "m06_acgan", "W"),
    ("WGAN-GP", "E8", "m07_wgangp", "W"),
    ("BAGAN", "E8", "m08_bagan", "W"),
    ("Proposed", "E1", "m10_ab8c", "W"),
]
# Class 0 is the majority class (pool and test 1000 : 50 : 50 on Fashion-MNIST); names as in Table A5.
CLASSES = {"fashion_mnist": ["Pullover", "Coat", "Shirt"], "cifar10": ["airplane", "automobile", "ship"],
           "stl10": ["cat", "dog", "deer"]}
DS_NAME = {"fashion_mnist": "Fashion-MNIST", "cifar10": "CIFAR-10", "stl10": "STL-10"}


def _runs(exp: str) -> pd.DataFrame:
    return pd.read_csv(os.path.join(SAVED, exp, "runs.csv"))


def collect() -> tuple:
    rows, cms = [], {}
    for ds, (rid, _r) in P.ANCHORS.items():
        for label, exp, prefix, arm in METHODS:
            runs = _runs(exp)
            for s in P.SEEDS:
                f = os.path.join(SAVED, exp, "predictions", f"{prefix}__{rid}__s{s}__{arm}.npz")
                z = np.load(f)
                y, yp = z["y_true"], z["y_pred"]
                K = len(CLASSES[ds])
                cm = np.zeros((K, K))
                np.add.at(cm, (y, yp), 1)
                rec = np.diag(cm) / cm.sum(axis=1)
                with np.errstate(invalid="ignore", divide="ignore"):
                    prec = np.where(cm.sum(axis=0) > 0, np.diag(cm) / cm.sum(axis=0), 0.0)
                tag = "isqrt" if prefix.endswith("_isqrt") else None
                method = prefix.replace("_isqrt", "")
                r = runs[(runs["regime"] == rid) & (runs["seed"] == s) & (runs["method"] == method)
                         & (runs["arm"] == arm)]
                if tag:
                    r = r[r["tag"] == tag]
                if len(r) != 1 or abs(float(r["macro_recall"].iloc[0]) - rec.mean()) > 1e-9:
                    raise SystemExit(f"{f}: macro-recall check failed ({len(r)} run rows)")
                cms.setdefault((ds, label), []).append(cm / cm.sum(axis=1, keepdims=True))
                for k, name in enumerate(CLASSES[ds]):
                    rows.append({"dataset": ds, "method": label, "seed": s, "class": name, "minority": k > 0,
                                 "recall": rec[k], "precision": prec[k]})
    return pd.DataFrame(rows), {k: np.mean(v, axis=0) for k, v in cms.items()}


def latex(summ: pd.DataFrame) -> str:
    lines = ["% Generated by kbs2/classwise.py from the saved predictions of Table 6; do not edit.",
             r"\begin{table}[htbp]", r"\centering",
             r"\caption{\rev{Class-wise recall and precision on the test set for the ten methods of "
             r"Table~\ref{tbl:cs_all}, mean over the ten seeds. The first class of each dataset is the majority "
             r"class; the other two are the minority classes. The best mean in each column of each dataset block "
             r"is set in bold. Figure~\ref{fig:confusion} gives the confusion matrices.}}",
             r"\label{tbl:classwise}", r"\resizebox{\linewidth}{!}{", r"\begin{tabular}{llcccccc}", r"\toprule"]
    for b, ds in enumerate(CLASSES):
        names = CLASSES[ds]
        hdr = " & ".join(rf"\multicolumn{{2}}{{c}}{{\rev{{{n}{' (majority)' if k == 0 else ''}}}}}"
                         for k, n in enumerate(names))
        lines.append(rf"\rev{{{DS_NAME[ds]}}} & & {hdr} \\")
        lines.append(r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}")
        lines.append(r" & \rev{Method} & " + " & ".join([r"\rev{Recall} & \rev{Precision}"] * 3) + r" \\")
        lines.append(r"\midrule")
        g = summ[summ["dataset"] == ds]
        best = {(c, m): g[(g["class"] == c)][m].round(3).max() for c in names for m in ("recall", "precision")}
        for label, *_ in METHODS:
            cells = []
            for c in names:
                for m in ("recall", "precision"):
                    v = g[(g["method"] == label) & (g["class"] == c)][m].iloc[0]
                    s = f"{v:.3f}"
                    cells.append(rf"\rev{{$\mathbf{{{s}}}$}}" if round(v, 3) == best[(c, m)] else rf"\rev{{${s}$}}")
            lines.append(rf" & \rev{{{label}}} & " + " & ".join(cells) + r" \\")
        lines.append(r"\midrule" if b < 2 else r"\bottomrule")
    lines += [r"\end{tabular}}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def figure(cms: dict) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    # Authors 13 Oct: 6 x 5 panels - two rows of five methods per dataset, in the row order of Table 6.
    fig, axes = plt.subplots(6, 5, figsize=(10, 12.5))
    for i, ds in enumerate(CLASSES):
        names = CLASSES[ds]
        for j, (label, *_) in enumerate(METHODS):
            r, c = 2 * i + j // 5, j % 5
            ax = axes[r, c]
            m = cms[(ds, label)]
            ax.imshow(m, cmap="Blues", vmin=0, vmax=1)
            for a in range(3):
                for b in range(3):
                    ax.text(b, a, f"{m[a, b]:.2f}", ha="center", va="center", fontsize=8,
                            color="white" if m[a, b] > 0.6 else "black")
            ax.set_xticks(range(3)); ax.set_yticks(range(3))
            ax.set_xticklabels(names, rotation=0, fontsize=6.5)
            ax.set_yticklabels(names if c == 0 else [""] * 3, fontsize=7.5)
            ax.tick_params(length=0)
            ax.set_title(label.replace(r"\ ", " "), fontsize=9)
        for r in (2 * i, 2 * i + 1):
            axes[r, 0].set_ylabel(DS_NAME[ds], fontsize=10, fontweight="bold")
    fig.tight_layout(pad=0.4, h_pad=0.8)   # rows: true class; columns: predicted class (stated in the caption)
    fig.savefig(FIG, bbox_inches="tight")


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    per_seed, cms = collect()
    per_seed.to_csv(os.path.join(OUT, "classwise_per_seed.csv"), index=False)
    summ = (per_seed.groupby(["dataset", "method", "class", "minority"], sort=False)[["recall", "precision"]]
            .agg(["mean", "std"]))
    summ.columns = ["recall", "recall_sd", "precision", "precision_sd"]
    summ = summ.reset_index()
    summ.to_csv(os.path.join(OUT, "classwise_summary.csv"), index=False)
    for (ds, label), m in cms.items():
        pd.DataFrame(m, index=CLASSES[ds], columns=CLASSES[ds]).to_csv(
            os.path.join(OUT, f"confusion__{ds}__{label.replace(chr(92), '').replace(' ', '_')}.csv"))
    with open(TEX, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(latex(summ))
    figure(cms)
    pd.set_option("display.width", 200)
    print(summ.round(3).to_string(index=False))


if __name__ == "__main__":
    main()

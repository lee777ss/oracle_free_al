"""kbs2.table6_stats - the pre-specified statistics (E4, kbs2.analysis) on Table 6 as published (R1.7).

    python -m kbs2.table6_stats      # writes saved_kbs2/analysis/E4_table6/

Authors 13 Oct 2026, option (a): the analysis fixed before E1 in ``kbs2.analysis`` (two-sided Wilcoxon
signed-rank, Holm over every comparison of a dataset block, Hodges-Lehmann estimate with exact 95% CI,
matched-pairs rank-biserial, Friedman), applied to the ten rows of Table 6 (classifier seed 42). The test
code is ``analysis.compare_block`` unchanged; only the row sources follow the remedy variants the authors
fixed for Table 6 on 11 Oct (they postdate ``analysis.main_table``, which still points at E2):
    seven submitted methods      submitted per-seed values (reproduced by E1/E8 to 1e-16)
    class-weighted               E2t, n01_class_weighted, tag isqrt (inverse-square-root weights), arm W
    random oversampling          E2z, n02_ros, arm U (unweighted CE)
    standard augmentation        E2s, n08_stdaug_budget_zc32 (pad 10, 32x32 zoom crop), arm W
Computed after the choice of option (a) and before any of its output was seen.

Authors, later on 13 Oct: one-sided tests (H1: the proposed method has the higher macro-F2), as in the
submitted paper, replace the two-sided tests of option (a). The two-sided results had been computed and
shown by then (they are kept in table6_comparisons_two_sided.csv); the authors' reason is the directional
hypothesis of the comparison. Everything else is unchanged: Holm over the nine comparisons of a dataset,
Hodges-Lehmann estimate with exact two-sided 95% CI, matched-pairs rank-biserial, Friedman over ten methods.
"""
from __future__ import annotations

import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from kbs2 import protocol as P  # noqa: E402
from kbs2.analysis import ALPHA, compare_block, holm, kbs2_rows, per_seed, submitted_rows  # noqa: E402

OUT = os.path.join(ROOT, "saved_kbs2", "analysis", "E4_table6")
TEX = os.path.join(ROOT, "Journal_paper_02_kbs_revise2", "src", "generated", "rev2_significance.tex")
DS_NAME = {"fashion_mnist": "Fashion-MNIST", "cifar10": "CIFAR-10", "stl10": "STL-10"}


def one_sided_p(d) -> float:
    """Exact one-sided Wilcoxon signed-rank p for H1: proposed > other (p = 1 if every difference is 0)."""
    import numpy as np
    from scipy.stats import wilcoxon
    d = np.asarray(d, dtype=float)
    if np.all(d == 0):
        return 1.0
    return float(wilcoxon(d, zero_method="wilcox", alternative="greater", method="auto").pvalue)


def _s(x: float, nd: int = 3) -> str:
    """Signed number; a value that rounds to zero is printed unsigned (0.000, not -0.000)."""
    v = round(float(x), nd)
    return f"{0.0:.{nd}f}" if v == 0 else f"{v:+.{nd}f}"


def _p(x: float) -> str:
    return "$<0.001$" if x < 0.001 else f"{x:.3f}"


def _chi(f) -> str:
    p = f["friedman_p"]
    ps = f"{p:.1e}".replace("e-0", r"\times10^{-") + "}" if p < 0.001 else f"{p:.3f}"
    return rf"$\chi^2 = {f['friedman_chi2']:.2f}$, $p = {ps}$"


def latex(c: pd.DataFrame, f: pd.DataFrame) -> str:
    """Table A4 (tbl:significance), every cell in the revision colour."""
    lines = ["% Generated by kbs2/table6_stats.py from saved_kbs2/analysis/E4_table6; do not edit.",
             r"\begin{table}[htbp]", r"\centering",
             r"\caption{\rev{One-sided Wilcoxon signed-rank tests of the proposed method against each of the nine "
             r"other methods of Table~\ref{tbl:cs_all} on macro-$F2$, paired by seed (ten seeds); $p$ adjusted by "
             r"Holm over the nine comparisons of a dataset. Difference: proposed minus the other method; HL: "
             r"Hodges--Lehmann estimate of the paired difference with its exact 95\% confidence interval; $r$: "
             r"matched-pairs rank-biserial correlation. The Friedman test is over the ten methods.}}",
             # 17 Oct 2026 (authors: larger tables): 10 pt, dataset and Friedman test as a row above each block
             r"\label{tbl:significance}", r"\footnotesize\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{lcccccc}",
             r"\toprule",
             r"\rev{Competing method} & \rev{Difference} & \rev{HL [95\% CI]} & "
             r"\rev{Holm $p$} & \rev{$r$} & \rev{Sig.} \\", r"\midrule"]
    for k, (ds, g) in enumerate(c.groupby("block", sort=False)):
        fr = f[f["block"] == ds].iloc[0]
        lines.append(rf"\multicolumn{{6}}{{l}}{{\rev{{\textit{{{DS_NAME[ds]}}}, Friedman {_chi(fr)}}}}} \\")
        for i, (_, r) in enumerate(g.iterrows()):
            cells = [rf"\rev{{{r['label']}}}", rf"\rev{{${_s(r['mean_diff'])}$}}",
                     rf"\rev{{${_s(r['hl'])}$ [${_s(r['ci_low'])}$, ${_s(r['ci_high'])}$]}}",
                     rf"\rev{{{_p(r['p_holm'])}}}", rf"\rev{{${_s(r['r_rb'], 2)}$}}",
                     r"\rev{Yes}" if r["p_holm"] < ALPHA else r"\rev{No}"]
            lines.append(" & ".join(cells) + r" \\")
        lines.append(r"\midrule" if k < 2 else r"\bottomrule")
    lines += [r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"
REMEDIES = [  # (experiment, method in its runs.csv, tag, arm, name used here, label)
    ("E2t", "n01_class_weighted", "isqrt", "W", "n01_class_weighted_isqrt", "Class-weighted"),
    ("E2z", "n02_ros", "", "U", "n02_ros_unweighted", "Random oversampling"),
    ("E2s", "n08_stdaug_budget_zc32", "", "W", "n08_stdaug_budget_zc32", r"Std.\ augmentation"),
]


def table6_rows(rid: str) -> pd.DataFrame:
    parts = [submitted_rows(rid, P.ORIGINAL_FIELD)]
    for exp, method, tag, arm, name, _ in REMEDIES:
        r = kbs2_rows(exp, arm, tag=tag, regime=rid, methods=[method])
        if len(r) != len(P.SEEDS):
            raise SystemExit(f"{exp} {method} {tag} {arm} {rid}: {len(r)} rows")
        parts.append(r.assign(method=name))
    return pd.concat(parts, ignore_index=True)


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    # Row order of Table 6 (authors 13 Oct): naive baseline, the three remedies, the five generative rivals.
    field = (["m11_imbalanced_naive"] + [name for *_, name, _ in REMEDIES]
             + P.GENERATIVE_RIVALS + [P.PROPOSED])
    assert sorted(field) == sorted(P.ORIGINAL_FIELD + [name for *_, name, _ in REMEDIES])
    labels = {name: label for *_, name, label in REMEDIES}
    descs, comps, frs = [], [], []
    for ds, (rid, _r) in P.ANCHORS.items():
        rows = table6_rows(rid)
        d, c, f = compare_block(rows, field, ds)
        d["label"] = d["method"].map(labels).fillna(d["label"])
        c["label"] = c["versus"].map(lambda m: labels.get(m, P.LABELS.get(m, m)))
        a = per_seed(rows, P.PROPOSED, "macro_f2")
        c["p"] = [one_sided_p(a - per_seed(rows, m, "macro_f2")) for m in c["versus"]]
        c["p_holm"] = holm(c["p"].tolist())
        c["verdict"] = ["proposed better" if q < ALPHA else "inconclusive" for q in c["p_holm"]]
        c = c.drop(columns=["W"])
        descs.append(d); comps.append(c); frs.append(f)
    d, c, f = pd.concat(descs), pd.concat(comps), pd.DataFrame(frs)
    d.to_csv(os.path.join(OUT, "table6_desc.csv"), index=False)
    c.to_csv(os.path.join(OUT, "table6_comparisons.csv"), index=False)
    f.to_csv(os.path.join(OUT, "table6_friedman.csv"), index=False)
    with open(TEX, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(latex(c, f))
    pd.set_option("display.width", 220)
    print(d[["block", "label", "macro_f2_mean", "macro_f2_sd", "n_seeds"]].round(4).to_string(index=False))
    print(c[["block", "label", "mean_diff", "hl", "ci_low", "ci_high", "p", "p_holm", "r_rb", "verdict"]]
          .round(4).to_string(index=False))
    print(f.round(5).to_string(index=False))


if __name__ == "__main__":
    main()

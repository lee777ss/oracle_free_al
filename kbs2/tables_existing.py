def _read(path: str) -> pd.DataFrame:
    d = pd.read_csv(path)
    if "error" in d:
        d = d[d["error"].isna() | (d["error"].astype(str) == "")]
    return d


def _ms(x: pd.Series) -> str:
    return f"${x.mean():.3f} \\pm {x.std(ddof=1):.3f}$"


# The ratios Table 7 (tbl:rho) shows; Table A5 gives class counts for these only.
TABLE7_RHO = {"fashion_mnist": (0.05, 0.10, 0.20), "cifar10": (0.10, 0.20, 0.30),
              "stl10": (0.10, 0.20, 0.30)}


def counts_table() -> str:
    from sklearn.model_selection import StratifiedShuffleSplit
    import cs3j_runner as r
    cfg = P.submitted_config()
    lines = [HEADER, r"\begin{table}[htbp]", r"\centering",
             r"\caption{\rev{Class counts of the nine regimes of Table~\ref{tbl:rho} (majority : minority : minority). The pool is drawn once from the official training split; a stratified 10\% hold-out is set aside before any augmenter is fitted; every augmenter adds $\Delta_c$ images per minority class to the training portion in $T$ acquisition cycles (proposed method). The test set is drawn from the official test split in the same way, except on STL-10, where all 800 test images per class are kept.}}",
             r"\label{tbl:data_counts}", r"\scalebox{0.58}{", r"\begin{tabular}{llcccccccc}", r"\toprule",
             r"Dataset & Classes & $\rho$ & Pool & Training portion & Hold-out & Test & $r$ & $\Delta_c$ & $T$ \\", r"\midrule"]
    for ds, (rid, ratio) in P.ANCHORS.items():
        cells = sorted([(rid, P.ANCHOR_RHO[rid])] + P.GRID_SWEEP[ds], key=lambda t: t[1])
        cells = [c for c in cells if c[1] in TABLE7_RHO[ds]]
        for i, (cid, rho) in enumerate(cells):
            reg = r.REGIMES[cid]
            spec = r.regime_spec(cfg.datasets[reg.get("dataset", "fashion_mnist")], cid, reg)
            pool = np.load(cfg.cache_path(spec.name, "trainpool"))
            test = np.load(cfg.cache_path(spec.name, "test"))
            y, yt = pool["labels"], test["labels"]
            tr, ho = next(StratifiedShuffleSplit(1, test_size=0.1, random_state=cfg.random_seed)
                          .split(np.zeros(len(y)), y))
            cnt = lambda a: [int((a == k).sum()) for k in range(3)]
            ctr = cnt(y[tr])
            tgt = [ctr[0]] + [int(min(ctr[0], max(n, round(ratio * n)))) for n in ctr[1:]]
            delta = tgt[1] - ctr[1]
            names = ", ".join(str(n) for n in pool["class_names"]) if i == 0 else ""
            star = r"$^{\ast}$" if cid == rid else ""
            lines.append(f"{DS_LABEL[ds] if i == 0 else ''} & {names} & {rho:g}{star} & "
                         f"{':'.join(map(str, cnt(y)))} & {':'.join(map(str, ctr))} & "
                         f"{':'.join(map(str, cnt(y[ho])))} & {':'.join(map(str, cnt(yt)))} & "
                         f"{ratio} & {delta} & {math.ceil(delta / 20)} \\\\")
        lines.append(r"\midrule" if ds != "stl10" else r"\bottomrule")
    lines += [r"\end{tabular}}",
              r"\par\smallskip{\footnotesize $^{\ast}$ Regime of Table~\ref{tbl:cs_all}. The ablation regime (Table~\ref{tbl:case_data}, first row) uses the pipeline of Section~\ref{subsec:ablation}.}",
              r"\end{table}"]
    return "\n".join(lines) + "\n"



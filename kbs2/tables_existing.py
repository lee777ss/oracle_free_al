def ablation_table() -> str:
    d = pd.read_csv(os.path.join(ROOT, "ablation_15_seeds.csv"))
    d = d[d["section"].astype(str).str.startswith("seed_")].copy()
    cols = {"recall": "Recall", "gmean": "G-mean", "f2": "$F2$", "specificity": "Specificity"}
    for c in cols:
        d[c] = pd.to_numeric(d[c], errors="coerce")
    seeds = sorted(d["seed"].astype(int).unique())
    groups = {row: d[d["row"] == row] for row, *_ in ABL_ROWS}
    bold = {c: _bold([(g[c].mean(), g[c].std(ddof=1)) for g in groups.values()]) for c in cols}
    lines = [HEADER, r"\begin{table}[htbp]", r"\centering",
             rf"\caption{{Ablation study on the ablation regime of Table~\ref{{tbl:case_data}}: \rev{{mean $\pm$ standard deviation over {len(seeds)} seeds ({seeds[0]}--{seeds[-1]}). Panel A: each generative backbone is combined with uncertainty (margin) sampling and with the proposed rule, and co-training is added to the BAGAN-GP model with the proposed rule; Variants 1 and 4 are Variants 1 and 2 of the submitted single-seed table. Panel B: selection rules with the same generator, the same candidates in every cycle and the same budget, with co-training off, on the data of panel A and with the protocol of Section~\ref{{subsec:settings}}. \emph{{Confidence + Diversity}} is the rule of Section~\ref{{subsec:selection}}; \emph{{Confidence only}} admits candidates that pass the gate at random, and \emph{{Diversity only}} applies the diversity step to all candidates. The two panels follow different protocols: panel A reports the classifier trained inside the acquisition loop, at the checkpoint selected on the hold-out, with a schedule and budget specific to each row, whereas panel B reports a classifier trained afresh with a common initialisation and a common budget; values are therefore compared within a panel, not across panels. The best mean in each column of each panel is set in bold; where two means are equal, the one with the smaller standard deviation.}}}}",
             r"\label{tbl:ablation}", r"\resizebox{\linewidth}{!}{", r"\begin{tabular}{lllccccc}", r"\toprule",
             r" & Generative & Selection & Co- & Recall & G-mean & $F2$ & Specificity \\",
             r" & model & & training & & & & \\", r"\midrule",
             r"\multicolumn{8}{l}{\rev{\textit{Panel A: backbone and selection rule}}} \\"]
    for i, (row, label, bb, sel, co) in enumerate(ABL_ROWS):
        g = groups[row]
        if len(g) != len(seeds):
            raise RuntimeError(f"{row}: {len(g)} seeds")
        cells = []
        for c in cols:
            s = f"{g[c].mean():.3f} \\pm {g[c].std(ddof=1):.3f}"
            cells.append(f"$\\mathbf{{{s}}}$" if bold[c][i] else f"${s}$")
        if row in ABL_NEW_ROWS:  # not in the submitted table: the whole row in the revision colour
            cells = [rf"\rev{{{x}}}" for x in cells]
            bb, co = rf"\rev{{{bb}}}", rf"\rev{{{co}}}"
        lines.append(f"{label} & {bb} & {sel} & {co} & " + " & ".join(cells) + r" \\")
    lines += panel_b()
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def panel_b() -> list:
    """Rows of Table 3 panel B from the AB runs (15 seeds per arm), every cell in the revision colour."""
    b = pd.read_csv(AB_RUNS)
    cols = ["macro_recall", "gmean", "macro_f2", "macro_specificity"]
    m = b.groupby(["cotrain", "rule"])[cols].agg(["mean", "std"])
    if (b.groupby(["cotrain", "rule"]).size() != 15).any() or len(m) != 16:
        raise RuntimeError("panel B needs 16 arms x 15 seeds")
    bold = {c: _bold([(m.loc[(False, mode), (c, "mean")], m.loc[(False, mode), (c, "std")])
                      for mode, _ in AB_RULES]) for c in cols}
    out = [r"\midrule", r"\multicolumn{8}{l}{\rev{\textit{Panel B: selection rules with the same generator, candidates and budget}}} \\"]
    for i, (mode, name) in enumerate(AB_RULES):
        cells = []
        for c in cols:
            mu, sd = m.loc[(False, mode), (c, "mean")], m.loc[(False, mode), (c, "std")]
            s = f"{mu:.3f} \\pm {sd:.3f}"
            cells.append(rf"\rev{{$\mathbf{{{s}}}$}}" if bold[c][i] else rf"\rev{{${s}$}}")
        out.append(f" & \\rev{{BAGAN-GP}} & \\rev{{{name}}} & \\rev{{No}} & " + " & ".join(cells) + r" \\")
    return out



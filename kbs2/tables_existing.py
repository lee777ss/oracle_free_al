def _bold(stats: list) -> list:
    """Which (mean, sd) pairs to set in bold: the best mean at three decimals; among rows tied
    on it, the smallest standard deviation at three decimals (authors, 13 Oct 2026)."""
    r = [(f"{mu:.3f}", f"{sd:.3f}") for mu, sd in stats]
    top = max(m for m, _ in r)
    sd_min = min(s for m, s in r if m == top)
    return [m == top and s == sd_min for m, s in r]



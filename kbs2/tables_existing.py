def s1_table() -> str:
    lines = [HEADER, r"\begin{table}[htbp]", r"\centering",
             r"\caption{\rev{Methods run on the same pools, hold-out splits, seeds and downstream protocol as Table~\ref{tbl:cs_all} but not reported in the submitted manuscript; mean $\pm$ standard deviation over ten seeds. The first row is the classifier without augmentation trained with unweighted cross-entropy and selected on validation macro-$F2$. BAGAN is shown without the label smoothing used in Table~\ref{tbl:cs_all}.}}",
             r"\label{tbl:s1}", r"\scalebox{0.6}{", r"\begin{tabular}{llcccc}", r"\toprule",
             r"Dataset & Method & Recall & G-mean & $F2$ & Specificity \\", r"\midrule"]
    for ds, (rid, _r) in P.ANCHORS.items():
        d = _read(os.path.join(ROOT, P.REFERENCE_FULL8_CSV[rid]))
        for i, m in enumerate(S1_METHODS):
            g = d[d["method"] == m]
            lines.append(f"{DS_LABEL[ds] if i == 0 else ''} & {S1_LABEL[m]} & " +
                         " & ".join(_ms(g[c]) for c in M4) + r" \\")
        lines.append(r"\midrule" if ds != "stl10" else r"\bottomrule")
    lines += [r"\end{tabular}}", r"\end{table}"]
    return "\n".join(lines) + "\n"


S2_METHODS = ["m11_imbalanced_naive", "m02_bsmote", "m04_dcgan", "m05_cgan", "m06_acgan",
              "m07_wgangp", "m08_bagan", "m10_ab8c"]
S2_HEAD = ["Imb.-naive", "B-SMOTE", "DCGAN", "cGAN", "ACGAN", "WGAN-GP", "BAGAN", "Proposed"]


def s2_table() -> str:
    lines = [HEADER, r"\begin{table}[htbp]", r"\centering",
             r"\caption{\rev{The imbalance-ratio grid as run: macro-$F2$, mean over ten seeds, for every ratio and every method of the grid runs (Borderline-SMOTE included). Rows marked $^{\ast}$ are the regimes of Table~\ref{tbl:cs_all}; Table~\ref{tbl:rho} shows three ratios per dataset. The best value in each row is set in bold.}}",
             r"\label{tbl:s2}", r"\scalebox{0.56}{", r"\begin{tabular}{llc" + "c" * len(S2_METHODS) + "}",
             r"\toprule", r"Dataset & $\rho$ & $n_{\min}$ & " + " & ".join(S2_HEAD) + r" \\", r"\midrule"]
    nmaj = {"fashion_mnist": 800, "cifar10": 1000, "stl10": 400}
    for ds, (rid, _r) in P.ANCHORS.items():
        cells = sorted([(rid, P.ANCHOR_RHO[rid])] + P.GRID_SWEEP[ds], key=lambda t: t[1])
        for i, (cid, rho) in enumerate(cells):
            d = _read(os.path.join(ROOT, P.reference_grid_csv(ds, cid)))
            vals = [d[d["method"] == m]["macro_f2"].mean() for m in S2_METHODS]
            b = max(vals)
            txt = [f"\\textbf{{{v:.3f}}}" if abs(v - b) < 1e-12 else f"{v:.3f}" for v in vals]
            star = r"$^{\ast}$" if cid == rid else ""
            lines.append(f"{DS_LABEL[ds] if i == 0 else ''} & {rho:g}{star} & {int(round(rho * nmaj[ds]))} & "
                         + " & ".join(txt) + r" \\")
        lines.append(r"\midrule" if ds != "stl10" else r"\bottomrule")
    lines += [r"\end{tabular}}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    os.makedirs(OUTDIR, exist_ok=True)
    for name, fn in [("rev2_counts", counts_table), ("rev2_ablation", ablation_table),
                     ("rev2_s1", s1_table), ("rev2_s2", s2_table)]:
        path = os.path.join(OUTDIR, f"{name}.tex")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(fn())
        print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
